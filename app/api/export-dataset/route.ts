import { NextRequest, NextResponse } from 'next/server';
import fs from 'fs/promises';
import path from 'path';
import { createObjectCsvWriter } from 'csv-writer';
import archiver from 'archiver';
import { Readable } from 'stream';

const DATA_DIR = path.join(process.cwd(), 'data', 'recordings', 'spa');
const AUDIO_DIR = path.join(DATA_DIR, 'audio');
const TRANSCRIPT_DIR = path.join(DATA_DIR, 'transcripts');

interface RecordingMetadata {
    file_name: string;
    speaker_id: string;
    age: number;
    gender: string;
    language: string;
    dialect: string;
    duration_sec: number;
    recording_device: string;
    notes: string;
}

async function generateMetadata(): Promise<RecordingMetadata[]> {
    const audioFiles = await fs.readdir(AUDIO_DIR);
    const wavFiles = audioFiles.filter(f => f.endsWith('.wav'));

    const metadata: RecordingMetadata[] = [];

    for (const file of wavFiles) {
        // Extract speaker ID from filename (spa_0001_001.wav)
        const match = file.match(/spa_(\d{4})_\d{3}\.wav/);
        const speakerId = match ? match[1] : '0000';

        metadata.push({
            file_name: file,
            speaker_id: speakerId,
            age: 0, // Will be filled from user data in future enhancement
            gender: 'Unknown',
            language: 'Spanish',
            dialect: 'Latin American',
            duration_sec: 30, // Approximate, could calculate from file
            recording_device: 'Browser WebRTC',
            notes: 'Recorded via Spanish Annotator Platform'
        });
    }

    return metadata;
}

async function createDatasetZip(): Promise<Buffer> {
    return new Promise(async (resolve, reject) => {
        const archive = archiver('zip', { zlib: { level: 9 } });
        const chunks: Buffer[] = [];

        archive.on('data', (chunk) => chunks.push(chunk));
        archive.on('end', () => resolve(Buffer.concat(chunks)));
        archive.on('error', (err) => reject(err));

        // Add audio files
        const audioFiles = await fs.readdir(AUDIO_DIR);
        for (const file of audioFiles) {
            const filePath = path.join(AUDIO_DIR, file);
            archive.file(filePath, { name: `spa/audio/${file}` });
        }

        // Add transcript files
        const transcriptFiles = await fs.readdir(TRANSCRIPT_DIR);
        for (const file of transcriptFiles) {
            const filePath = path.join(TRANSCRIPT_DIR, file);
            archive.file(filePath, { name: `spa/transcripts/${file}` });
        }

        // Generate and add metadata.csv
        const metadata = await generateMetadata();
        const csvPath = path.join(DATA_DIR, 'metadata.csv');

        const csvWriter = createObjectCsvWriter({
            path: csvPath,
            header: [
                { id: 'file_name', title: 'file_name' },
                { id: 'speaker_id', title: 'speaker_id' },
                { id: 'age', title: 'age' },
                { id: 'gender', title: 'gender' },
                { id: 'language', title: 'language' },
                { id: 'dialect', title: 'dialect' },
                { id: 'duration_sec', title: 'duration_sec' },
                { id: 'recording_device', title: 'recording_device' },
                { id: 'notes', title: 'notes' }
            ]
        });

        await csvWriter.writeRecords(metadata);
        archive.file(csvPath, { name: 'spa/metadata.csv' });

        // Add README
        const readme = `# Spanish TTS Training Dataset

## Dataset Information
- Language: Spanish
- Recording Quality: 24kHz, PCM 16-bit, Mono
- Format: WAV
- Transcript Format: SSML-tagged text files

## Folder Structure
/spa/
    /audio/          - WAV audio files (24kHz, PCM 16-bit)
    /transcripts/    - Text transcripts with SSML tags
    metadata.csv     - Speaker metadata and recording info

## File Naming Convention
Format: spa_XXXX_YYY.wav
- spa: Language code (Spanish)
- XXXX: Speaker ID (4 digits)
- YYY: Sample ID (3 digits)

## Usage
This dataset is suitable for training TTS models, voice cloning, and speech synthesis systems.

Generated by Spanish Annotator Platform
`;
        archive.append(readme, { name: 'spa/README.md' });

        archive.finalize();
    });
}

export async function GET(request: NextRequest) {
    try {
        const zipBuffer = await createDatasetZip();

        return new NextResponse(zipBuffer, {
            headers: {
                'Content-Type': 'application/zip',
                'Content-Disposition': `attachment; filename="spanish_tts_dataset_${Date.now()}.zip"`,
            },
        });
    } catch (error: any) {
        console.error('Export error:', error);
        return NextResponse.json(
            { error: error.message || 'Failed to export dataset' },
            { status: 500 }
        );
    }
}
